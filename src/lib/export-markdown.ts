import { OAuthGuide } from '@/types/oauth';

export function generateMarkdownBrief(guide: OAuthGuide): string {
  const prerequisites = [
    guide.prerequisites.paidAccountRequired ? 'Paid Account Required' : 'Free Tier Supported',
    guide.prerequisites.domainVerificationRequired ? 'Domain Verification Required (DNS/HTML)' : 'No Domain Verification',
    guide.prerequisites.privacyPolicyRequired ? 'Public Privacy Policy Required' : 'No Public Privacy Policy Required',
    guide.prerequisites.securityAssessmentRequired ? 'Security Assessment / Audit Required (e.g. CASA/SOC2)' : 'No Security Assessment Required',
    ...guide.prerequisites.notes,
  ];

  const stepsMd = guide.steps
    .map(
      (s) => `### Step ${s.stepNumber}: ${s.title} [${s.actor.replace('_', ' ')}]
- **Actor Rationale:** ${s.actorRationale}
- **Action:** ${s.description}
${s.actionUrl ? `- **Console Link:** ${s.actionUrl}\n` : ''}${
        s.codeSnippet
          ? `\`\`\`
${s.codeSnippet}
\`\`\`\n`
          : ''
      }${
        s.pitfalls && s.pitfalls.length > 0
          ? `- **Pitfalls / Traps:**\n${s.pitfalls.map((p) => `  - ⚠️ ${p}`).join('\n')}\n`
          : ''
      }`
    )
    .join('\n');

  const sourcesMd = guide.verification.sources
    .map((s) => `- [${s.title}](${s.url})`)
    .join('\n');

  const verifiedClaimsMd = guide.verification.verifiedClaims
    .map((c) => `- ✅ ${c}`)
    .join('\n');

  const uncertaintiesMd = guide.verification.uncertaintiesOrCaveats
    .map((u) => `- ⚠️ ${u}`)
    .join('\n');

  return `# OAuth Integration Brief: ${guide.appName}
**Category:** ${guide.category} | **Auth Type:** ${guide.authType}
**Difficulty:** ${guide.difficulty} | **Agent Automation:** ${guide.agentAutomationPercentage}%

> **Executive Summary:** ${guide.summary}

---

## ⏱️ Effort & Approval Timeline
- **Active Developer Effort:** ~${guide.estimatedDevTimeMinutes} minutes
- **Provider Approval Queue:** ${guide.estimatedApprovalWaitDays}
- **App Review Required:** ${guide.requiresAppReview ? 'Yes (Review approval blocks launch)' : 'No (Instant self-serve)'}

## 📋 Prerequisites & Blockers
${prerequisites.map((p) => `- ${p}`).join('\n')}

## 🔑 Scopes & Redirect URI Nuances
- **Default Scopes:** \`${guide.scopesOverview.defaultScopes.join('`, `')}\`
${guide.scopesOverview.sensitiveScopesWarning ? `- **Sensitive Scopes Warning:** ${guide.scopesOverview.sensitiveScopesWarning}\n` : ''}
- **Redirect URI Rules:**
${guide.redirectUriNuances.map((r) => `  - ${r}`).join('\n')}

## 🛠️ Step-by-Step Setup Guide
${stepsMd}

## 🔍 Verification & Evidence Grounding
- **Verification Status:** ${guide.verification.status} (Last Verified: ${guide.verification.lastChecked})
- **Official Documentation Sources:**
${sourcesMd}
- **Verified Facts:**
${verifiedClaimsMd}
- **Caveats & Uncertainties:**
${uncertaintiesMd}

---
*Generated by OAuth Setup Navigator — Interactive APM Integrations Guide*
`;
}
